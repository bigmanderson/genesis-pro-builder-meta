// Deterministic generator: App Intent -> InSpatial universal project files (Kit client + Cloud server).
// Scaffolds with the official CLI (`inspatial create ... --shape universal`), then writes intent-specific
// Cloud entries (schema), API actions, seed data, ISS style.ts and the entry window.
import type { Intent } from "./pipeline.ts";
import { kitFiles, kitPlan } from "./kit_ui.ts";

const camel = (s: string) => s.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : "")).replace(/^./, (c) => c.toLowerCase());
const pascal = (s: string) => camel(s).replace(/^./, (c) => c.toUpperCase());
export const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 30) || "app";

const FIELD: Record<string, string> = {
  text: "TextField", email: "TextField", phone: "TextField", date: "TextField", image: "TextField",
  number: "IntField", money: "CurrencyField", boolean: "BooleanField", choice: "ChoicesField",
};

export function inspatialFiles(intent: Intent, slug: string): Record<string, string> {
  const files: Record<string, string> = {};
  const app = camel(slug);
  const entries = intent.entities.map((e) => {
    const name = camel(e.name);
    const fields = e.fields.map((f) => {
      const t = FIELD[f.type] ?? "TextField";
      const choices = t === "ChoicesField" && f.choices?.length
        ? `,\n      choices: [${f.choices.map((c) => `{ key: ${JSON.stringify(camel(c))}, label: ${JSON.stringify(c)} }`).join(", ")}]`
        : "";
      return `    {\n      key: ${JSON.stringify(camel(f.key))},\n      type: "${t}",\n      label: ${JSON.stringify(f.label)}${f.required ? ",\n      required: true" : ""}${choices},\n    }`;
    }).join(",\n");
    const title = camel(e.fields[0]?.key ?? "title");
    return { name, code: `export const ${name}Entry = defineEntry(${JSON.stringify(name)}, {\n  label: ${JSON.stringify(e.name)},\n  titleField: ${JSON.stringify(title)},\n  defaultListFields: [${e.fields.slice(0, 3).map((f) => JSON.stringify(camel(f.key))).join(", ")}],\n  fields: [\n${fields},\n  ],\n});` };
  });
  files["server/src/app/entry.ts"] = `import { defineEntry } from "@inspatial/cloud";\n\n/*################################(GENERATED BY GENESIS PRO BUILDER)################################*/\n// Source intent: ${intent.app_name} (${intent.kind})\n\n${entries.map((e) => e.code).join("\n\n")}\n\nexport const entries = [${entries.map((e) => `${e.name}Entry`).join(", ")}];\n`;
  files["server/src/app/api.ts"] = `import { defineAPIGroup } from "@inspatial/cloud";\n\nexport const ${app}API = defineAPIGroup(${JSON.stringify(app)}, {\n  label: ${JSON.stringify(intent.app_name + " API")},\n  description: ${JSON.stringify(intent.summary)},\n});\n\n${app}API.addAction("ping", { label: "Ping", description: "Health check", action: () => ({ ok: true }), params: [] });\n` +
    intent.actions.map((a) => `\n// ${a.description}\n${app}API.addAction(${JSON.stringify(camel(a.name))}, {\n  label: ${JSON.stringify(a.name)},\n  description: ${JSON.stringify(a.description)},\n  action: ({ params }) => ({ ok: true, params }),\n  params: [],\n});\n`).join("");
  files["server/src/app/seed.ts"] = `// Seed data extracted from the input photo (SAM 3.1 counts + Muse Spark reading).\nexport const seed = ${JSON.stringify(Object.fromEntries(intent.seed.map((s) => [camel(s.entity), s.rows.map((r) => Object.fromEntries(r.map((kv) => [camel(kv.key), kv.value])))])), null, 2)} as const;\n`;
  files["server/src/global/extension.ts"] = `import { defineExtension } from "@inspatial/cloud";\nimport { ${app}API } from "../app/api.ts";\nimport { entries } from "../app/entry.ts";\nimport { ${app}Settings } from "../app/settings.ts";\n\nexport const ${pascal(slug)}Extension = defineExtension(${JSON.stringify(pascal(slug))}, {\n  label: ${JSON.stringify(intent.app_name)},\n  version: "1.0.0",\n  description: ${JSON.stringify(intent.summary)},\n  entryTypes: entries,\n  apiGroups: [${app}API],\n  settingsTypes: [${app}Settings],\n});\n`;
  // Client: InSpatial Kit showcase UI (hero, image cards, stock bars, working Cloud-backed actions). See lib/kit_ui.ts.
  Object.assign(files, kitFiles(intent));
  files["(moodboard)/intent.json"] = JSON.stringify(intent, null, 2);
  return files;
}

export async function scaffold(dir: string, slug: string, intent: Intent, visual?: { imageDataUrl: string; segs: { prompt: string; dets: unknown[] }[] }): Promise<{ ok: boolean; log: string; files: string[]; preview?: Record<string, string> }> {
  await Deno.mkdir(dir, { recursive: true });
  let log = "";
  try {
    const cmd = new Deno.Command("inspatial", { args: ["create", slug, "--category", "app", "--shape", "universal", "--yes"], cwd: dir, stdout: "piped", stderr: "piped", env: { NO_COLOR: "1" } });
    const o = await cmd.output();
    log = new TextDecoder().decode(o.stdout) + new TextDecoder().decode(o.stderr);
    if (!o.success) return { ok: false, log, files: [] };
  } catch (e) { return { ok: false, log: String(e), files: [] }; }
  const files = inspatialFiles(intent, slug);
  for (const [rel, src] of Object.entries(files)) {
    const p = `${dir}/${slug}/${rel}`;
    await Deno.mkdir(p.slice(0, p.lastIndexOf("/")), { recursive: true });
    await Deno.writeTextFile(p, src);
  }
  // Item art: the input photo as the hero + SAM 3.1 box crops per item (tools/inspatial_assets.py). Optional.
  if (visual?.imageDataUrl?.startsWith("data:image")) {
    try {
      const tmp = await Deno.makeTempFile({ suffix: ".img" });
      await Deno.writeFile(tmp, Uint8Array.from(atob(visual.imageDataUrl.split(",")[1]), (c) => c.charCodeAt(0)));
      const spec = JSON.stringify({ items: kitPlan(intent).seed.map((s) => s.name), segs: visual.segs.map((s) => ({ prompt: s.prompt, dets: s.dets })) });
      const ax = await new Deno.Command("python3", { args: [new URL("../tools/inspatial_assets.py", import.meta.url).pathname, `${dir}/${slug}`, tmp, spec], stdout: "piped", stderr: "piped" }).output();
      log += "\n[assets] " + new TextDecoder().decode(ax.stdout) + new TextDecoder().decode(ax.stderr).slice(-400);
      await Deno.remove(tmp).catch(() => {});
    } catch (e) { log += `\n[assets] skipped: ${e}`; }
  }
  // Optional local post-generation step (not included in this repository); skipped when absent.
  try {
    const fxPath = new URL("../tools/inspatial_postfix.py", import.meta.url).pathname;
    await Deno.stat(fxPath);
    const fx = await new Deno.Command("python3", { args: [fxPath, `${dir}/${slug}`], stdout: "piped", stderr: "piped" }).output();
    log += "\n[postfix] " + new TextDecoder().decode(fx.stdout) + new TextDecoder().decode(fx.stderr);
  } catch (_e) { log += "\n[postfix] skipped"; }
  return { ok: true, log: log.replace(/\x1b\[[0-9;]*m/g, ""), files: Object.keys(files), preview: { "server/src/app/entry.ts": files["server/src/app/entry.ts"], "client/src/app/entry/style.ts": files["client/src/app/entry/style.ts"], "client/src/app/entry/window.tsx": files["client/src/app/entry/window.tsx"] } };
}
