#!/usr/bin/env python3
"""Writes item art for a generated InSpatial project from the user's input photo.
hero = the photo itself; each SAM 3.1 prompt's best box becomes a square crop matched to a seed item by word overlap.
Usage: inspatial_assets.py <project_dir> <input_image> <json: {"items":[names], "segs":[{"prompt":str,"dets":[{x1,y1,x2,y2,w,h}]}]}>"""
import json, os, re, sys
from PIL import Image
proj, src, spec = sys.argv[1], sys.argv[2], json.loads(sys.argv[3])
out = os.path.join(proj, 'client/src/asset/gpb'); os.makedirs(out, exist_ok=True)
im = Image.open(src).convert('RGB'); W, H = im.size
hw = min(W, 1600); im.resize((hw, int(H * hw / W)), Image.LANCZOS).save(os.path.join(out, 'hero.jpg'), quality=85)
words = lambda s: set(w for w in re.findall(r'[a-z]+', s.lower()) if len(w) > 2 and w not in {'the', 'and', 'with', 'glass', 'paper', 'bottle', 'bottles', 'jar', 'jars', 'bag', 'bags', 'tin', 'tins'})
art = {'__hero': '/asset/gpb/hero.jpg'}
for i, seg in enumerate(spec.get('segs', [])):
    dets = seg.get('dets') or []
    if not dets: continue
    d = sorted(dets, key=lambda d: (d['x2'] - d['x1']) * (d['y2'] - d['y1']))[len(dets) // 2]
    sx, sy = W / (d.get('w') or W), H / (d.get('h') or H)
    x1, y1, x2, y2 = d['x1'] * sx, d['y1'] * sy, d['x2'] * sx, d['y2'] * sy
    cx, cy, s = (x1 + x2) / 2, (y1 + y2) / 2, max(x2 - x1, y2 - y1) * 1.12
    box = [max(0, cx - s / 2), max(0, cy - s / 2), min(W, cx + s / 2), min(H, cy + s / 2)]
    name = f'item-{i}.jpg'
    im.crop(tuple(int(v) for v in box)).resize((480, 480), Image.LANCZOS).save(os.path.join(out, name), quality=88)
    pw = words(seg['prompt'])
    best = max(spec.get('items', []), key=lambda n: len(words(n) & pw), default=None)
    if best and words(best) & pw and best not in art: art[best] = f'/asset/gpb/{name}'
open(os.path.join(proj, 'client/src/app/entry/art.ts'), 'w').write(
    '// Item art for the entry window: the input photo and SAM 3.1 box crops of it (generated by Genesis Pro Builder).\n'
    f'export const ShelfArt: Record<string, string> = {json.dumps(art, indent=2)};\n')
print(f'assets: hero + {len(art) - 1} item crops')
